"""
Проверки обезличивания персональных данных.

Запуск:
    python test_anonymizer.py
    make test
"""

from __future__ import annotations

import sys

from anonymizer import (
    address_form,
    anonymize,
    capitalize_names_in_text,
    natural_name_order,
    person_parts,
    restore,
)

PASSED = 0
FAILED: list[str] = []


def check(condition: bool, message: str) -> None:
    global PASSED
    if condition:
        PASSED += 1
    else:
        FAILED.append(message)


def check_equal(actual, expected, message: str) -> None:
    check(actual == expected, f"{message}\n     получено: {actual!r}\n     ожидалось: {expected!r}")


def case(text: str, known=()) -> str:
    return anonymize(text, known_values=known).text


# ---------------------------------------------------------------------------
print("Проверка 1. Точные значения из формы заменяются везде")
# ---------------------------------------------------------------------------
result = anonymize(
    "Имя: Иван Петров\nТелефон: +7 900 123-45-67\n\nЗдравствуйте, Иван Петров! "
    "Пишите на ivanov@company.ru или звоните +7 900 123-45-67.",
    known_values=["Иван Петров", "+7 900 123-45-67", "ivanov@company.ru"],
)
text = result.text
check("[ИМЯ_1]" in text, "имя из формы заменено")
check("[ТЕЛЕФОН_1]" in text, "телефон из формы заменён")
check("[ПОЧТА_1]" in text, "почта из формы заменена")
check("Иван Петров" not in text, "имени в тексте не осталось")
check("+7 900 123-45-67" not in text, "телефона в тексте не осталось")
check("ivanov@company.ru" not in text, "почты в тексте не осталось")
check(text.count("[ИМЯ_1]") == 2, "имя заменено во всех вхождениях")
check_equal(result.mapping["[ИМЯ_1]"], "Иван Петров", "соответствие имени")
check_equal(result.mapping["[ТЕЛЕФОН_1]"], "+7 900 123-45-67", "соответствие телефона")

# ---------------------------------------------------------------------------
print("Проверка 2. Персональные данные внутри текста заявки")
# ---------------------------------------------------------------------------
result = anonymize(
    "Меня зовут Иван Петров, тел. 8 900 123-45-67, почта ivanov@company.ru. "
    "Доставка по адресу: ул. Пушкина, 12, кв. 5, Санкт-Петербург."
)
text = result.text
check("[ИМЯ_1]" in text, "ФИО в тексте найдено")
check("[ТЕЛЕФОН_1]" in text, "телефон в тексте найден")
check("[ПОЧТА_1]" in text, "почта в тексте найден")
check("[АДРЕС_1]" in text, "адрес в тексте найден")
check("Иван Петров" not in text, "ФИО удалено")
check("8 900 123-45-67" not in text, "телефон удалён")
check("Пушкина" not in text, "адрес удалён")

# ---------------------------------------------------------------------------
print("Проверка 3. Форматы телефонов")
# ---------------------------------------------------------------------------
for phone in [
    "+7 900 123-45-67",
    "8 (900) 123-45-67",
    "8-900-123-45-67",
    "900 123 45 67",
    "900-123-45-67",
    "+79001234567",
    "тел. 9001234567",
    "мобильный +7 900 123 45 67",
]:
    text = case(f"Мой телефон {phone}, звоните удобно.")
    check(f"[ТЕЛЕФОН_1]" in text, f"телефон не распознан: {phone}")
    check(phone not in text, f"телефон не заменён: {phone}")

# ---------------------------------------------------------------------------
print("Проверка 4. Имена и отчества")
# ---------------------------------------------------------------------------
for name, must_vanish in [
    ("Иван Петров", "Иван Петров"),
    ("Пётр Сидоров", "Пётр Сидоров"),
    ("Анна Сергеевна", "Анна Сергеевна"),
    ("Мария", "Мария"),
    ("Обращайтесь к Марии (отдел закупок)", "Марии"),
]:
    text = case(f"Здравствуйте! {name}, подскажите условия.")
    check("[ИМЯ_1]" in text, f"имя не распознано: {name}")
    check(must_vanish not in text, f"имя не заменено: {must_vanish}")

text = case("Заявка от Иванова И.И., тел. +7 900 000-00-00")
check("[ИМЯ_1]" in text, "фамилия с инициалами распознана")
check("Иванов" not in text, "фамилия заменена")

# ---------------------------------------------------------------------------
print("Проверка 5. Адреса")
# ---------------------------------------------------------------------------
for address in [
    "ул. Ленина, д. 5, кв. 12",
    "на проспекте Мира, 44",
    "переулок Лесной, 3",
    "набережная Фонтанки, 15",
]:
    text = case(f"Доставка: {address}, город Екатеринбург")
    check("[АДРЕС_1]" in text, f"адрес не распознан: {address}")

text = case("Пришлите, пожалуйста, в Санкт-Петербург")
check("[АДРЕС_1]" in text, "город в контексте распознан")

text = case("Доставка по адресу: ул. Пушкина, 12, кв. 5, Санкт-Петербург.")
check(text == "Доставка по адресу: [АДРЕС_1].", f"полный адрес распознан целиком: {text}")
check("Пушкина" not in text and "Санкт-Петербург" not in text, "адрес скрыт полностью")

text = case("Москва, ул. Тверская, 1, офис 15")
check(text == "[АДРЕС_1]", f"город перед адресом попал в токен: {text}")

# Название улицы без типа («Новый Арбат, 10») — ловится по маркеру «по адресу»
text = case("Наш офис находится в Москве, по адресу Новый Арбат, 10.")
check("[АДРЕС_1]" in text and "[АДРЕС_2]" in text, f"город и улица без типа: {text}")
check("Новый Арбат" not in text, "название улицы скрыто")

for phrase in [
    "по адресу Тверская, 5",
    "Адрес доставки: Тверская, 5",
    "Отправляйте на адрес Солянка, 16",
    "Мы находимся по адресу: Большая Дмитровка, 15, офис 3",
]:
    text = case(phrase)
    check("[АДРЕС_1]" in text, f"адрес без типа не распознан: {phrase}")

# «Столы, 20 штук» — не адрес, даже если рядом есть слово «адрес»
for phrase in [
    "Укажите адрес для доставки: Стул офисный, 20 штук.",
    "Нужно 20 комплектов мебели. Адрес для доставки уточним позже. Столы, 20 штук.",
    "Адрес пока не известен, перезвоните.",
]:
    text = case(phrase)
    check(text == phrase, f"ложное срабатывание на адрес: {phrase!r} -> {text!r}")

# ---------------------------------------------------------------------------
print("Проверка 6. Реквизиты")
# ---------------------------------------------------------------------------
text = case("ИНН 7707083893, СНИЛС 123-456-789 00, карта 4276 1234 5678 9012")
check("[ИНН_1]" in text, "ИНН распознан")
check("[СНИЛС_1]" in text, "СНИЛС распознан")
check("[КАРТА_1]" in text, "карта распознана")
check("7707083893" not in text, "ИНН удалён")
check("4276 1234 5678 9012" not in text, "карта удалена")

text = case("родился 12.05.1985, прошу прислать коммерческое предложение")
check("[ДАТА_РОЖДЕНИЯ_1]" in text, "дата рождения распознана")
check("12.05.1985" not in text, "дата рождения удалена")

# ---------------------------------------------------------------------------
print("Проверка 7. НЕ должно меняться")
# ---------------------------------------------------------------------------
for safe in [
    "500 000 рублей",
    "20 офисных столов и 40 кресел",
    "до конца месяца",
    "ООО «ОфисЛайн», отдел закупок",
    "ИП Ромашка",
    "кресло Атлант",
    "CRM-система для отдела продаж",
    "поставка 1 200 000 единиц",
    "за 3 рабочих дня",
    "1 000 000 000 рублей",
]:
    text = case(f"Нужно: {safe}. Подскажите условия.")
    check(text == f"Нужно: {safe}. Подскажите условия.", f"испорчено: {safe!r} -> {text!r}")

# ---------------------------------------------------------------------------
print("Проверка 8. Обратная подстановка")
# ---------------------------------------------------------------------------
original = (
    "Имя: Иван Петров\nТелефон: +7 900 123-45-67\n\n"
    "Здравствуйте, Иван Петров! Нужны столы и кресла."
)
result = anonymize(original, known_values=["Иван Петров", "+7 900 123-45-67"])
restored = restore(result.text, result.mapping)
check_equal(restored, original, "текст восстановлен полностью")

# Модель могла переписать токен в другом регистре или без скобок
check("Иван Петров" in restore("[ИМЯ_1] и [ИМЯ_1]", {"[ИМЯ_1]": "Иван Петров"}), "скобочный токен")
check("Иван Петров" in restore("[имя_1]", {"[ИМЯ_1]": "Иван Петров"}), "токен в другом регистре")
check("Иван Петров" in restore("ИМЯ_1", {"[ИМЯ_1]": "Иван Петров"}), "токен без скобок")
check("[НЕТ]" in restore("[НЕТ]", {"[ИМЯ_1]": "Иван Петров"}), "чужой токен не тронут")

# ---------------------------------------------------------------------------
print("Проверка 9. Соответствие не попадает в результат")
# ---------------------------------------------------------------------------
result = anonymize("Иван Петров, +7 900 123-45-67", known_values=["Иван Петров"])
check(all("value" not in item for item in result.findings), "в findings нет значений")
check(all("+7 900" not in str(item) for item in result.findings), "в findings нет телефонов")
check(result.summary.count("телефон") == 1, "сводка содержит типы")

# ---------------------------------------------------------------------------
print("Проверка 10. Пустые и нестандартные входные данные")
# ---------------------------------------------------------------------------
check(anonymize("").text == "", "пустой текст")
check(anonymize("   ").text == "   ", "текст из пробелов")
result = anonymize("Ничего персонального тут нет", known_values=["", None])
check(result.text == "Ничего персонального тут нет", "текст без ПД не меняется")

# ---------------------------------------------------------------------------
print("Проверка 11. Регистр имён")
# ---------------------------------------------------------------------------
result = anonymize("Добрый день! Меня зовут иван.", known_values=[])
check_equal(result.mapping.get("[ИМЯ_1]"), "Иван", "Имя сохраняется с большой буквы")
check_equal(
    restore("Здравствуйте, [ИМЯ_1]!", result.mapping),
    "Здравствуйте, Иван!",
    "После восстановления имя с большой буквы",
)
check(
    capitalize_names_in_text("Напишите ивану") == "Напишите Ивану",
    "Падежная форма имени тоже поднимается",
)
check(
    capitalize_names_in_text("Нужны столы, марка Атлант, бюджет 500 000 рублей.")
    == "Нужны столы, марка Атлант, бюджет 500 000 рублей.",
    "Обычные слова не задеваются",
)

# ---------------------------------------------------------------------------
print("Проверка 12. Форма обращения и порядок имени")
# ---------------------------------------------------------------------------
check_equal(person_parts("Савельева Мария"), ("Мария", "", "Савельева"), "Фамилия и имя разобраны")
check_equal(person_parts("Мария Савельева"), ("Мария", "", "Савельева"), "Имя и фамилия разобраны")
check_equal(person_parts("Петров Иван Петрович"), ("Иван", "Петрович", "Петров"), "Имя, отчество и фамилия")
check_equal(natural_name_order("Савельева Мария"), "Мария Савельева", "Порядок имени привычный")
check_equal(natural_name_order("Иван Петров"), "Иван Петров", "Порядок не меняется зря")
check_equal(address_form("Савельева Мария"), "Мария", "Форма обращения — по имени")
check_equal(address_form("Петров Иван Петрович"), "Иван Петрович", "Форма обращения — имя и отчество")

from app import fix_greeting_name, fix_name_capitalization

check_equal(
    fix_greeting_name("Здравствуйте, Савельева Мария! Спасибо.", "Савельева Мария"),
    "Здравствуйте, Мария! Спасибо.",
    "В приветствии — только имя",
)
check_equal(
    fix_greeting_name("Здравствуйте, это компания ОфисЛайн!", "Савельева Мария"),
    "Здравствуйте, это компания ОфисЛайн!",
    "Посторонний текст после приветствия не тронут",
)
card = fix_name_capitalization(
    {
        "reply_draft": "Здравствуйте, иван! Спасибо.",
        "key_data": {"name": "иван петров"},
    }
)
check_equal(card["key_data"]["name"], "Иван Петров", "Имя в карточке с большой буквы")
check_equal(card["reply_draft"], "Здравствуйте, Иван! Спасибо.", "Имя в черновике с большой буквы")

# ---------------------------------------------------------------------------
print()
print(f"Пройдено проверок: {PASSED}")
if FAILED:
    print(f"ПРОВАЛЕНО: {len(FAILED)}")
    for item in FAILED:
        print(f"  ✗ {item}")
    sys.exit(1)

print("Все проверки пройдены.")
